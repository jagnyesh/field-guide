"""Turns captured runner output (lib/fixtures/<runner>/*.txt) into lib/fixtures/<runner>.ts, since
tests run without file access. Re-run after capturing new output."""
import json
import os
import sys

root = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "lib", "fixtures")
for runner in sorted(os.listdir(root)):
    folder = os.path.join(root, runner)
    if not os.path.isdir(folder):
        continue
    entries = {}
    for name in sorted(os.listdir(folder)):
        if name.endswith(".txt"):
            entries[name[:-4]] = open(os.path.join(folder, name)).read()
    lines = ["// Generated by scripts/fixtures-to-ts.py from lib/fixtures/%s/*.txt; do not edit." % runner,
             "export const OUTPUT: Readonly<Record<string, string>> = {"]
    lines += ["  %s: %s," % (json.dumps(key), json.dumps(value)) for key, value in entries.items()]
    lines.append("}")
    open(os.path.join(root, runner + ".ts"), "w").write("\n".join(lines) + "\n")
    print("wrote", runner + ".ts", len(entries), "outputs")
